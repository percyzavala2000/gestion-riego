CREATE TABLE conceptos_cobro (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(120) NOT NULL,
 descripcion VARCHAR(500),
 activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE cuentas_cobrar (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(30) NOT NULL UNIQUE,
 agricultor_id BIGINT NOT NULL REFERENCES agricultores(id),
 concepto_id BIGINT NOT NULL REFERENCES conceptos_cobro(id),
 monto_total NUMERIC(12,2) NOT NULL CHECK (monto_total > 0),
 monto_pagado NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (monto_pagado >= 0),
 fecha_emision DATE NOT NULL,
 fecha_vencimiento DATE NOT NULL,
 estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
 observaciones VARCHAR(500),
 motivo_anulacion VARCHAR(500),
 fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_cuentas_agricultor ON cuentas_cobrar(agricultor_id);
CREATE INDEX idx_cuentas_estado_vencimiento ON cuentas_cobrar(estado, fecha_vencimiento);
