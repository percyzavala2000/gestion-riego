CREATE TABLE notificaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 agricultor_id BIGINT REFERENCES agricultores(id) ON DELETE CASCADE,
 usuario_id BIGINT REFERENCES usuarios(id) ON DELETE CASCADE,
 tipo VARCHAR(40) NOT NULL,
 titulo VARCHAR(160) NOT NULL,
 mensaje VARCHAR(1000) NOT NULL,
 prioridad VARCHAR(15) NOT NULL DEFAULT 'MEDIA',
 estado VARCHAR(15) NOT NULL DEFAULT 'NO_LEIDA',
 referencia_tipo VARCHAR(40),
 referencia_id BIGINT,
 referencia_url VARCHAR(255),
 clave_idempotencia VARCHAR(180) NOT NULL UNIQUE,
 fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 fecha_lectura TIMESTAMPTZ,
 fecha_archivado TIMESTAMPTZ,
 fecha_expiracion TIMESTAMPTZ,
 CONSTRAINT chk_notificacion_destinatario CHECK ((agricultor_id IS NOT NULL)::int + (usuario_id IS NOT NULL)::int = 1),
 CONSTRAINT chk_notificacion_prioridad CHECK (prioridad IN ('BAJA','MEDIA','ALTA','CRITICA')),
 CONSTRAINT chk_notificacion_estado CHECK (estado IN ('NO_LEIDA','LEIDA','ARCHIVADA'))
);
CREATE INDEX idx_notificacion_agricultor_estado_fecha ON notificaciones(agricultor_id,estado,fecha_creacion DESC);
CREATE INDEX idx_notificacion_usuario_estado_fecha ON notificaciones(usuario_id,estado,fecha_creacion DESC);
CREATE INDEX idx_notificacion_expiracion ON notificaciones(fecha_expiracion) WHERE fecha_expiracion IS NOT NULL;
