CREATE TABLE dispositivos_push (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuenta_agricultor_id BIGINT NOT NULL REFERENCES cuentas_agricultor(id) ON DELETE CASCADE,
  firebase_installation_id VARCHAR(180) NOT NULL,
  token_registro VARCHAR(4096) NOT NULL,
  plataforma VARCHAR(15) NOT NULL,
  nombre_dispositivo VARCHAR(120),
  version_aplicacion VARCHAR(30),
  version_sistema VARCHAR(40),
  modelo_dispositivo VARCHAR(100),
  idioma VARCHAR(20),
  zona_horaria VARCHAR(60),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion_token TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_ultimo_uso TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_desactivacion TIMESTAMPTZ,
  CONSTRAINT uk_dispositivo_push_cuenta_fid UNIQUE(cuenta_agricultor_id, firebase_installation_id),
  CONSTRAINT chk_dispositivo_push_plataforma CHECK(plataforma IN ('ANDROID','IOS'))
);
CREATE INDEX idx_dispositivo_push_cuenta_activo ON dispositivos_push(cuenta_agricultor_id, activo);
CREATE INDEX idx_dispositivo_push_ultimo_uso ON dispositivos_push(fecha_ultimo_uso);
