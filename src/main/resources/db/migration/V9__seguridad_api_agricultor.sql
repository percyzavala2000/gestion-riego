CREATE TABLE cuentas_agricultor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agricultor_id BIGINT NOT NULL UNIQUE REFERENCES agricultores(id),
    usuario VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    intentos_fallidos INTEGER NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
    bloqueado_hasta TIMESTAMPTZ,
    ultimo_acceso TIMESTAMPTZ,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sesiones_agricultor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id BIGINT NOT NULL REFERENCES cuentas_agricultor(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    identificador VARCHAR(64) NOT NULL UNIQUE,
    dispositivo VARCHAR(200),
    direccion_ip VARCHAR(64),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion TIMESTAMPTZ NOT NULL,
    fecha_ultimo_uso TIMESTAMPTZ,
    revocado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_revocacion TIMESTAMPTZ,
    reemplazado_por VARCHAR(64)
);

CREATE INDEX idx_cuenta_agricultor_usuario_activo
    ON cuentas_agricultor (lower(usuario), activo);
CREATE INDEX idx_sesion_agricultor_cuenta_estado
    ON sesiones_agricultor (cuenta_id, revocado, fecha_expiracion);
CREATE INDEX idx_sesion_agricultor_expiracion
    ON sesiones_agricultor (fecha_expiracion);
