CREATE TABLE entregas_push (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notificacion_id BIGINT NOT NULL REFERENCES notificaciones(id) ON DELETE CASCADE,
  dispositivo_push_id BIGINT NOT NULL REFERENCES dispositivos_push(id) ON DELETE CASCADE,
  estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
  proveedor VARCHAR(20) NOT NULL DEFAULT 'FIREBASE',
  mensaje_proveedor_id VARCHAR(255),
  codigo_error VARCHAR(100),
  detalle_error VARCHAR(600),
  intentos INTEGER NOT NULL DEFAULT 0,
  proximo_intento TIMESTAMPTZ,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_envio TIMESTAMPTZ,
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_entrega_push_notificacion_dispositivo UNIQUE(notificacion_id, dispositivo_push_id),
  CONSTRAINT chk_entrega_push_estado CHECK(estado IN ('PENDIENTE','ENVIADA','ERROR_TEMPORAL','ERROR_DEFINITIVO','CANCELADA')),
  CONSTRAINT chk_entrega_push_intentos CHECK(intentos >= 0)
);
CREATE INDEX idx_entrega_push_pendiente ON entregas_push(estado, proximo_intento, fecha_creacion);
