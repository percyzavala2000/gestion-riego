CREATE TABLE auditoria_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    correlacion_id VARCHAR(36) NOT NULL,
    usuario VARCHAR(50) NOT NULL,
    rol VARCHAR(30),
    metodo VARCHAR(10) NOT NULL,
    ruta VARCHAR(255) NOT NULL,
    codigo_http INTEGER NOT NULL,
    exitoso BOOLEAN NOT NULL,
    direccion_ip VARCHAR(64),
    agente_usuario VARCHAR(500)
);
CREATE INDEX idx_auditoria_fecha ON auditoria_eventos(fecha_hora DESC);
CREATE INDEX idx_auditoria_usuario_fecha ON auditoria_eventos(usuario, fecha_hora DESC);
CREATE INDEX idx_auditoria_ruta_fecha ON auditoria_eventos(ruta, fecha_hora DESC);
CREATE INDEX idx_auditoria_correlacion ON auditoria_eventos(correlacion_id);
